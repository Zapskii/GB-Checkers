#!/usr/bin/env python3
"""Board geometry generator for GB-Draughts -> board_geom.h

Standard English draughts uses only the 32 dark squares of an 8x8 board,
numbered row-major starting at the top-left dark square:

    row 0:  . 0 . 1 . 2 . 3
    row 1:  4 . 5 . 6 . 7 .
    row 2:  . 8 . 9 . 10. 11
    ...
    row 7:  28. 29. 30. 31.

Diagonal adjacency isn't uniform (row parity shifts the neighbor offsets),
so this script computes the 32x4 neighbor table once, self-checks it, and
emits it as committed, generated C data. The game never computes board
geometry at runtime - only array lookups.

Run `make geom` to regenerate; board_geom.h is committed so a plain `make`
needs no Python.
"""

N_SQ = 32
NO_SQ = 0xFF

# Direction indices, and each one's opposite (for the symmetry self-check).
DIR_NW, DIR_NE, DIR_SW, DIR_SE = 0, 1, 2, 3
OPPOSITE = {DIR_NW: DIR_SE, DIR_NE: DIR_SW, DIR_SW: DIR_NE, DIR_SE: DIR_NW}
DELTA = {DIR_NW: (-1, -1), DIR_NE: (-1, 1), DIR_SW: (1, -1), DIR_SE: (1, 1)}


def idx_to_coord(idx):
    row = idx // 4
    col = (1 if row % 2 == 0 else 0) + 2 * (idx % 4)
    return row, col


def coord_to_idx(row, col):
    if not (0 <= row < 8 and 0 <= col < 8):
        return None
    if (row + col) % 2 == 0:
        return None                      # light square: never a play square
    return row * 4 + (col - (1 if row % 2 == 0 else 0)) // 2


def build_neighbors():
    neigh = [[NO_SQ] * 4 for _ in range(N_SQ)]
    for idx in range(N_SQ):
        row, col = idx_to_coord(idx)
        for d, (dr, dc) in DELTA.items():
            n = coord_to_idx(row + dr, col + dc)
            neigh[idx][d] = n if n is not None else NO_SQ
    return neigh


def self_check(neigh):
    # Every idx<->coord mapping round-trips.
    for idx in range(N_SQ):
        row, col = idx_to_coord(idx)
        assert coord_to_idx(row, col) == idx, idx

    # Symmetry: if A's neighbor in dir d is B, B's neighbor in the opposite
    # direction is A. This is the geometry equivalent of GB-Protector's
    # torus_dx brute-force cross-check - catch a bad offset here, not on
    # hardware.
    for idx in range(N_SQ):
        for d in range(4):
            other = neigh[idx][d]
            if other == NO_SQ:
                continue
            assert neigh[other][OPPOSITE[d]] == idx, (idx, d, other)

    # Every neighbor is a genuine dark square distinct from idx itself.
    seen_rowcols = {idx_to_coord(i) for i in range(N_SQ)}
    for idx in range(N_SQ):
        row, col = idx_to_coord(idx)
        assert (row, col) in seen_rowcols
        for d in range(4):
            other = neigh[idx][d]
            assert other != idx


def main():
    neigh = build_neighbors()
    self_check(neigh)

    # Black starts on rows 0-2 (squares 0-11), white on rows 5-7 (20-31),
    # rows 3-4 (12-19) empty. Black moves toward row 7, white toward row 0.
    black_start = sum(1 << i for i in range(0, 12))
    white_start = sum(1 << i for i in range(20, 32))
    assert black_start & white_start == 0

    lines = [
        "/* Generated by boardgen.py - do not edit. Run `make geom` to regenerate. */",
        "#ifndef BOARD_GEOM_H",
        "#define BOARD_GEOM_H",
        "",
        "#include <stdint.h>",
        "",
        "#define N_SQ    32",
        "#define NO_SQ   0xFFu",
        "",
        "#define DIR_NW  0",
        "#define DIR_NE  1",
        "#define DIR_SW  2",
        "#define DIR_SE  3",
        "",
        "/* Black starts top (rows 0-2), moves toward row 7 (SW/SE) to promote.",
        " * White starts bottom (rows 5-7), moves toward row 0 (NW/NE) to promote. */",
        "#define BLACK_START 0x%08Xu" % black_start,
        "#define WHITE_START 0x%08Xu" % white_start,
        "#define BLACK_KING_ROW_MIN 28u   /* squares 28-31 */",
        "#define WHITE_KING_ROW_MAX 3u    /* squares 0-3   */",
        "",
        "/* NEIGH[sq][DIR_*] = adjacent square in that direction, or NO_SQ. */",
        "static const uint8_t NEIGH[N_SQ][4] = {",
    ]
    for idx in range(N_SQ):
        vals = ", ".join(
            ("NO_SQ" if v == NO_SQ else "%2d" % v) for v in neigh[idx]
        )
        lines.append("    { %s },  /* %2d */" % (vals, idx))
    lines += ["};", "", "#endif", ""]

    with open("board_geom.h", "w") as f:
        f.write("\n".join(lines))
    print("board_geom.h: %d squares, self-check passed" % N_SQ)


if __name__ == "__main__":
    main()
